-- HIVE v11: optional group discussions setup for the existing Chat > Groups UI.
-- This file is intentionally NOT executed automatically. Existing tables and rows are not dropped.
-- Requires the normal HIVE schema (public.profiles and public.my_fields()) to be installed first.

begin;

create table if not exists public.hive_chat_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 3 and 80),
  description text not null default '',
  visibility text not null default 'public' check (visibility in ('public','private')),
  created_by uuid not null references auth.users(id) on delete cascade,
  community_id text not null default 'default',
  field text not null default 'education' check (field in ('education','medical')),
  created_at timestamptz not null default now()
);

create table if not exists public.hive_chat_group_members (
  group_id uuid not null references public.hive_chat_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','member')),
  joined_at timestamptz not null default now(),
  primary key (group_id,user_id)
);

create table if not exists public.hive_group_messages (
  id bigint generated by default as identity primary key,
  group_id uuid not null references public.hive_chat_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  author text not null default 'Member',
  body text not null check (char_length(trim(body)) between 1 and 500),
  created_at timestamptz not null default now()
);

create index if not exists hive_chat_groups_community_field_created_idx
  on public.hive_chat_groups (community_id,field,created_at desc);
create index if not exists hive_chat_group_members_user_idx
  on public.hive_chat_group_members (user_id,group_id);
create index if not exists hive_group_messages_group_created_idx
  on public.hive_group_messages (group_id,created_at desc);

alter table public.hive_chat_groups enable row level security;
alter table public.hive_chat_group_members enable row level security;
alter table public.hive_group_messages enable row level security;

-- Security-definer helpers keep RLS policies concise and avoid recursive group/member policies.
create or replace function public.hive_group_context_matches(p_community_id text,p_field text)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (
    select 1 from public.profiles p
    where p.id=auth.uid()
      and coalesce(p.community_id,'default')=coalesce(p_community_id,'default')
      and p_field=any(public.my_fields())
  );
$$;

create or replace function public.hive_group_context_for_id(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (
    select 1 from public.hive_chat_groups g
    where g.id=p_group_id and public.hive_group_context_matches(g.community_id,g.field)
  );
$$;

create or replace function public.hive_group_is_member(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (select 1 from public.hive_chat_group_members m where m.group_id=p_group_id and m.user_id=auth.uid());
$$;

create or replace function public.hive_group_is_owner(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (
    select 1 from public.hive_chat_groups g
    where g.id=p_group_id and g.created_by=auth.uid()
      and public.hive_group_context_matches(g.community_id,g.field)
  );
$$;

create or replace function public.hive_group_is_participant(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select public.hive_group_context_for_id(p_group_id)
    and (public.hive_group_is_member(p_group_id) or public.hive_group_is_owner(p_group_id));
$$;

create or replace function public.hive_group_is_public_joinable(p_group_id uuid)
returns boolean language sql stable security definer set search_path=public as $$
  select exists (
    select 1 from public.hive_chat_groups g
    where g.id=p_group_id and g.visibility='public'
      and public.hive_group_context_matches(g.community_id,g.field)
  );
$$;

-- The creator is automatically recorded as the group's owner/member.
create or replace function public.hive_group_add_creator_membership()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.hive_chat_group_members(group_id,user_id,role)
  values(new.id,new.created_by,'owner') on conflict(group_id,user_id) do nothing;
  return new;
end;
$$;
drop trigger if exists hive_group_creator_membership on public.hive_chat_groups;
create trigger hive_group_creator_membership after insert on public.hive_chat_groups
for each row execute function public.hive_group_add_creator_membership();

-- Group invitations are only available to the group owner and stay inside the same community/field.
create or replace function public.hive_invite_group_member(p_group_id uuid,p_username_or_email text)
returns boolean language plpgsql security definer set search_path=public as $$
declare
  grp public.hive_chat_groups%rowtype;
  target_user uuid;
  lookup_text text;
begin
  lookup_text:=lower(trim(coalesce(p_username_or_email,'')));
  if lookup_text='' then raise exception 'Enter a username or email.'; end if;

  select * into grp from public.hive_chat_groups g
  where g.id=p_group_id and g.created_by=auth.uid()
    and public.hive_group_context_matches(g.community_id,g.field);
  if grp.id is null then raise exception 'Only the group creator can invite members.'; end if;

  select p.id into target_user from public.profiles p
  where (lower(coalesce(p.email,''))=lookup_text
      or lower(coalesce(p.name,''))=lookup_text
      or lower(coalesce(p.roll_no,''))=lookup_text)
    and coalesce(p.community_id,'default')=coalesce(grp.community_id,'default')
    and (p.field=grp.field or coalesce(p.fields,array[p.field]) @> array[grp.field])
  limit 1;
  if target_user is null then raise exception 'No matching HIVE profile was found in this community and field.'; end if;

  insert into public.hive_chat_group_members(group_id,user_id,role)
  values(grp.id,target_user,'member') on conflict(group_id,user_id) do nothing;
  return true;
end;
$$;

-- Remove only this migration's named policies if it is re-run; unrelated HIVE policies are untouched.
drop policy if exists hgc_groups_read on public.hive_chat_groups;
create policy hgc_groups_read on public.hive_chat_groups for select to authenticated
using (public.hive_group_context_matches(community_id,field)
  and (visibility='public' or created_by=auth.uid() or public.hive_group_is_member(id)));

drop policy if exists hgc_groups_create on public.hive_chat_groups;
create policy hgc_groups_create on public.hive_chat_groups for insert to authenticated
with check (created_by=auth.uid() and public.hive_group_context_matches(community_id,field));

drop policy if exists hgc_members_read on public.hive_chat_group_members;
create policy hgc_members_read on public.hive_chat_group_members for select to authenticated
using (public.hive_group_context_for_id(group_id)
  and (user_id=auth.uid() or public.hive_group_is_owner(group_id)));

drop policy if exists hgc_members_join_public on public.hive_chat_group_members;
create policy hgc_members_join_public on public.hive_chat_group_members for insert to authenticated
with check (user_id=auth.uid() and role='member' and public.hive_group_is_public_joinable(group_id));

drop policy if exists hgc_members_leave_or_owner_remove on public.hive_chat_group_members;
create policy hgc_members_leave_or_owner_remove on public.hive_chat_group_members for delete to authenticated
using (public.hive_group_context_for_id(group_id)
  and (user_id=auth.uid() or public.hive_group_is_owner(group_id)));

drop policy if exists hgc_messages_read on public.hive_group_messages;
create policy hgc_messages_read on public.hive_group_messages for select to authenticated
using (public.hive_group_is_participant(group_id));

drop policy if exists hgc_messages_send on public.hive_group_messages;
create policy hgc_messages_send on public.hive_group_messages for insert to authenticated
with check (user_id=auth.uid() and public.hive_group_is_participant(group_id));

revoke all on function public.hive_group_context_matches(text,text) from public,anon;
revoke all on function public.hive_group_context_for_id(uuid) from public,anon;
revoke all on function public.hive_group_is_member(uuid) from public,anon;
revoke all on function public.hive_group_is_owner(uuid) from public,anon;
revoke all on function public.hive_group_is_participant(uuid) from public,anon;
revoke all on function public.hive_group_is_public_joinable(uuid) from public,anon;
revoke all on function public.hive_group_add_creator_membership() from public,anon;
revoke all on function public.hive_invite_group_member(uuid,text) from public,anon;
grant execute on function public.hive_group_context_matches(text,text) to authenticated;
grant execute on function public.hive_group_context_for_id(uuid) to authenticated;
grant execute on function public.hive_group_is_member(uuid) to authenticated;
grant execute on function public.hive_group_is_owner(uuid) to authenticated;
grant execute on function public.hive_group_is_participant(uuid) to authenticated;
grant execute on function public.hive_group_is_public_joinable(uuid) to authenticated;
grant execute on function public.hive_invite_group_member(uuid,text) to authenticated;

revoke all on public.hive_chat_groups,public.hive_chat_group_members,public.hive_group_messages from public,anon;
grant select,insert on public.hive_chat_groups to authenticated;
grant select,insert,delete on public.hive_chat_group_members to authenticated;
grant select,insert on public.hive_group_messages to authenticated;
grant usage,select on sequence public.hive_group_messages_id_seq to authenticated;

commit;

