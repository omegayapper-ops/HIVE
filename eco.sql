-- HIVE · EcoPoints admin  (run ONCE in Supabase → SQL Editor → Run)
-- Safe to run again: it never wipes activities you have added.
--
-- Adds:
--   • table  eco_activities          – the activity catalogue shown in EcoPoints
--   • rpc    ops_eco_get / ops_eco_do – used by the "EcoPoints" tab in ops.html
--                                       (protected by the same admin password
--                                        as every other tab, via admin_check)
--   • rpc    eco_activities_public    – read-only list the EcoPoints app loads
--
-- Requires the earlier HIVE setup (hive2.sql), because it re-uses the
-- admin_check(p_password) function that ops.html already signs in with.
-- =====================================================================

create table if not exists public.eco_activities (
  id          int  primary key generated by default as identity,
  cat         text not null default 'other'
                check (cat in ('plastic','recycle','tree','clean','water','other')),
  emoji       text not null default '🌿',
  title       text not null,
  description text not null default '',
  points      int  not null check (points between 1 and 1000),
  difficulty  text not null default 'Easy' check (difficulty in ('Easy','Medium','Hard')),
  image_url   text not null default '',
  active      boolean not null default true,
  sort_order  int  not null default 0,
  created_at  timestamptz not null default now()
);

-- No direct table access from the browser: everything goes through the
-- functions below.
alter table public.eco_activities enable row level security;

