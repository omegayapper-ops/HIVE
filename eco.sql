-- ---- admin password guard (re-uses HIVE's admin_check) --------------
create or replace function public._eco_guard(p_password text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not coalesce(public.admin_check(p_password), false) then
    raise exception 'INVALID_ADMIN_PASSWORD';
  end if;
end $$;
revoke all on function public._eco_guard(text) from public, anon, authenticated;

-- ---- row → json -----------------------------------------------------
create or replace function public._eco_row(r public.eco_activities)
returns jsonb language sql immutable as $$
  select jsonb_build_object(
    'id', r.id, 'cat', r.cat, 'emoji', r.emoji, 'title', r.title,
    'description', r.description, 'points', r.points, 'difficulty', r.difficulty,
    'image', r.image_url, 'active', r.active, 'sort_order', r.sort_order);
$$;
revoke all on function public._eco_row(public.eco_activities) from public, anon, authenticated;

-- ---- READ (admin panel) --------------------------------------------
create or replace function public.ops_eco_get(p_password text, p_what text)
returns jsonb language plpgsql security definer set search_path = public as $$
begin
  perform public._eco_guard(p_password);
  if p_what = 'activities' then
    return coalesce((select jsonb_agg(public._eco_row(a) order by a.sort_order, a.id)
                       from public.eco_activities a), '[]'::jsonb);
  end if;
  raise exception 'UNKNOWN_QUERY';
end $$;

-- ---- READ (the EcoPoints app – no password, nothing sensitive) -----
create or replace function public.eco_activities_public()
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public._eco_row(a) order by a.sort_order, a.id), '[]'::jsonb)
    from public.eco_activities a;
$$;

-- ---- WRITE (admin panel) -------------------------------------------
create or replace function public.ops_eco_do(p_password text, p_op text, p jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_title text; v_desc text; v_emoji text; v_cat text; v_diff text; v_img text;
  v_pts int;    v_id int;     v_ord int;     v_other record;
begin
  perform public._eco_guard(p_password);

  if p_op in ('add_activity','update_activity') then
    v_title := btrim(coalesce(p->>'title',''));
    v_desc  := btrim(coalesce(p->>'description',''));
    v_emoji := btrim(coalesce(nullif(p->>'emoji',''),'🌿'));
    v_cat   := coalesce(nullif(p->>'cat',''),'other');
    v_diff  := coalesce(nullif(p->>'difficulty',''),'Easy');
    v_img   := btrim(coalesce(p->>'image',''));
    begin v_pts := (p->>'points')::int; exception when others then v_pts := null; end;

    if char_length(v_title) < 3 or char_length(v_title) > 80 then
      raise exception 'Activity name must be 3 to 80 characters'; end if;
    if char_length(v_desc) > 200 then
      raise exception 'Description is too long (200 characters max)'; end if;
    if char_length(v_emoji) > 8 then
      raise exception 'Use a single emoji'; end if;
    if v_pts is null or v_pts < 1 or v_pts > 1000 then
      raise exception 'Points must be a whole number from 1 to 1000'; end if;
    if v_cat not in ('plastic','recycle','tree','clean','water','other') then
      raise exception 'Unknown category'; end if;
    if v_diff not in ('Easy','Medium','Hard') then
      raise exception 'Difficulty must be Easy, Medium or Hard'; end if;
    if v_img <> '' and (v_img !~* '^https://[^\s]+$' or char_length(v_img) > 500) then
      raise exception 'Image link must start with https://'; end if;
  end if;

  if p_op = 'add_activity' then
    insert into public.eco_activities (cat, emoji, title, description, points, difficulty, image_url, sort_order)
    values (v_cat, v_emoji, v_title, v_desc, v_pts, v_diff, v_img,
            coalesce((select max(sort_order) from public.eco_activities), 0) + 1)
    returning id into v_id;
    return jsonb_build_object('ok', true, 'id', v_id);

  elsif p_op = 'update_activity' then
    update public.eco_activities
       set cat = v_cat, emoji = v_emoji, title = v_title, description = v_desc,
           points = v_pts, difficulty = v_diff, image_url = v_img
     where id = (p->>'id')::int;
    if not found then raise exception 'Activity not found'; end if;
    return jsonb_build_object('ok', true);

  elsif p_op = 'set_active' then
    update public.eco_activities set active = coalesce((p->>'active')::boolean, true)
     where id = (p->>'id')::int;
    if not found then raise exception 'Activity not found'; end if;
    return jsonb_build_object('ok', true);

  elsif p_op = 'delete_activity' then
    delete from public.eco_activities where id = (p->>'id')::int;
    return jsonb_build_object('ok', true);

  elsif p_op = 'move_activity' then
    v_id := (p->>'id')::int;
    select sort_order into v_ord from public.eco_activities where id = v_id;
    if not found then raise exception 'Activity not found'; end if;
    if p->>'dir' = 'up' then
      select id, sort_order into v_other from public.eco_activities
       where (sort_order, id) < (v_ord, v_id) order by sort_order desc, id desc limit 1;
    else
      select id, sort_order into v_other from public.eco_activities
       where (sort_order, id) > (v_ord, v_id) order by sort_order, id limit 1;
    end if;
    if v_other.id is not null then
      -- swap; if two rows ever share a sort_order, separate them
      if v_other.sort_order = v_ord then
        update public.eco_activities set sort_order = v_ord + (case when p->>'dir'='up' then -1 else 1 end)
         where id = v_id;
      else
        update public.eco_activities set sort_order = v_other.sort_order where id = v_id;
        update public.eco_activities set sort_order = v_ord where id = v_other.id;
      end if;
    end if;
    return jsonb_build_object('ok', true);
  end if;

  raise exception 'UNKNOWN_OPERATION';
end $$;

