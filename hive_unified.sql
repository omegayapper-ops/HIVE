  create or replace function public.adm_profile(p_field text, p_action text, p_user uuid default null, p_email text default null)
  returns void language plpgsql security definer set search_path = public as $$
  declare v_id uuid;
  begin
    if not public.is_field_admin(p_field) then raise exception 'You are not an administrator of the % field', p_field; end if;
    v_id := p_user;
    if v_id is null and p_email is not null then select id into v_id from public.profiles where lower(email) = lower(p_email) limit 1; end if;
    if v_id is null then raise exception 'No account found with that username'; end if;
    if p_action = 'grant' then
      update public.profiles set fields = array(select distinct unnest(fields || array[p_field])) where id = v_id;
    elsif p_action = 'remove' then
      if v_id = auth.uid() then raise exception 'You cannot remove your own access'; end if;
      if (select array_length(array_remove(fields, p_field), 1) from public.profiles where id = v_id) is null then raise exception 'An account must keep at least one field'; end if;
      update public.profiles set fields = array_remove(fields, p_field) where id = v_id;
    else raise exception 'Unknown action'; end if;
  end $$;
  $f$;
