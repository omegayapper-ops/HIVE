-- v8 · ONE database, TWO workspaces (Education + Medical) and a separate admin panel for each
--   • every shared table gets a `field` column; existing rows stay in Education
--   • students can only read their own fields' data; field admins only manage their field
--   • profiles.fields = fields an account may open (all existing accounts: Education + Medical)
--   • profiles.admin_fields = fields an admin may manage (all existing admins: both)
